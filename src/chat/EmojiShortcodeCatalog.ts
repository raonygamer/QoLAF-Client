  public static scalarAt(index: number): number {
    return index >= 0 && index < EmojiShortcodeCatalog.ENTRY_COUNT
      ? EmojiPickerCatalog.scalarAtFlat(index)
      : 0;
  }

  public static shortNameAt(index: number): string {
    return index >= 0 && index < EmojiShortcodeCatalog.ENTRY_COUNT
      ? EmojiShortcodeCatalog.SHORT_NAMES[index]
      : '';
  }

  public static shortcodeAt(index: number): string {
    return index >= 0 && index < EmojiShortcodeCatalog.ENTRY_COUNT
      ? EmojiShortcodeCatalog.SHORTCODES[index]
      : '';
  }

  public static searchTermsAt(index: number): string {
    return index >= 0 && index < EmojiShortcodeCatalog.ENTRY_COUNT
      ? EmojiShortcodeCatalog.SEARCH_TERMS[index]
      : '';
  }

  public static emojiAt(index: number): string {
    return index >= 0 && index < EmojiShortcodeCatalog.ENTRY_COUNT
      ? EmojiShortcodeCatalog.emojiForScalar(EmojiPickerCatalog.scalarAtFlat(index))
      : '';
  }

  /** Returns the flat picker index for a supported scalar, or -1. */

  public static indexOfScalar(scalar: number): number {
    for (let index: number = 0; index < EmojiShortcodeCatalog.ENTRY_COUNT; index++) {
      if (EmojiPickerCatalog.scalarAtFlat(index) == scalar) return index;
    }
    return -1;
  }

  /** Converts a supported scalar to its renderable Unicode chat string. */

  public static emojiForScalar(scalar: number): string {
    if (EmojiGlyphLookup.glyphIdForScalar(scalar) < 0) return '';
    let result: string;
    if (scalar <= 0xffff) {
      result = String.fromCharCode(scalar);
    } else {
      let value: number = scalar - 0x10000;
      result = String.fromCharCode(0xd800 + (value >> 10), 0xdc00 + (value & 0x3ff));
    }
    if (EmojiGlyphLookup.requiresVS16(scalar)) {
      result += String.fromCharCode(EmojiGlyphLookup.VS16);
    }
    return result;
  }

  /**
   * Returns the unique canonical-shortcode index, or -1. CLDR keywords are
   * intentionally excluded so a closing colon can never resolve ambiguously.
   */

  public static findExact(query: string): number {
    let normalized: string = EmojiShortcodeCatalog.prepareQuery(query);
    if (normalized.length == 0) return -1;
    for (let index: number = 0; index < EmojiShortcodeCatalog.ENTRY_COUNT; index++) {
      if (EmojiShortcodeCatalog.SHORTCODES[index] == normalized) return index;
    }
    for (
      let aliasIndex: number = 0;
      aliasIndex < EmojiShortcodeCatalog.COMPATIBILITY_NAMES.length;
      aliasIndex++
    ) {
      if (
        EmojiShortcodeCatalog.COMPATIBILITY_NAMES[aliasIndex] ==
        EmojiShortcodeCatalog.cachedRawAliasQuery
      ) {
        return EmojiShortcodeCatalog.COMPATIBILITY_INDICES[aliasIndex];
      }
    }
    return -1;
  }

  /**
   * Ranks one entry for a normalized shortcode query. Lower is better:
   * exact canonical, canonical prefix, canonical word prefix, exact keyword,
   * keyword prefix, canonical substring, then keyword substring. An empty
   * query returns rank 1 for every entry so callers may show picker order.
   */

  public static matchRankAt(index: number, query: string): number {
    if (index < 0 || index >= EmojiShortcodeCatalog.ENTRY_COUNT) return -1;
    let normalized: string = EmojiShortcodeCatalog.prepareQuery(query);
    let shortcode: string = EmojiShortcodeCatalog.SHORTCODES[index];
    let compatibilityRank: number = EmojiShortcodeCatalog.compatibilityRankAt(index);
    if (normalized.length == 0) {
      return EmojiShortcodeCatalog.cachedRawAliasQuery.length == 0 ? 1 : compatibilityRank;
    }
    if (shortcode == normalized) return 0;
    if (compatibilityRank == 0) return 0;
    if (shortcode.indexOf(normalized) == 0) return 1;
    if (compatibilityRank == 1) return 1;
    if (shortcode.indexOf(EmojiShortcodeCatalog.cachedSegmentPrefix) >= 0) return 2;

    let terms: string = EmojiShortcodeCatalog.SEARCH_TERMS[index];
    if (terms.indexOf(EmojiShortcodeCatalog.cachedExactKeyword) >= 0) return 3;
    if (terms.indexOf(EmojiShortcodeCatalog.cachedKeywordPrefix) >= 0) return 4;
    if (shortcode.indexOf(normalized) >= 0) return 5;
    if (compatibilityRank == 5) return 5;
    if (terms.indexOf(normalized) >= 0) return 6;
    return -1;
  }

  /** Normalizes user input to the generated ASCII underscore convention. */

  public static normalizeQuery(query: string): string {
    return EmojiShortcodeCatalog.prepareQuery(query);
  }

  /** Cache normalization and delimiter needles across a 1,391-entry scan. */

  private static prepareQuery(query: string): string {
    query = query == null ? '' : query;
    if (query == EmojiShortcodeCatalog.cachedSourceQuery)
      return EmojiShortcodeCatalog.cachedNormalizedQuery;
    EmojiShortcodeCatalog.cachedSourceQuery = query;
    EmojiShortcodeCatalog.cachedRawAliasQuery = query.toLowerCase().replace(/^\s+|\s+$/g, '');
    EmojiShortcodeCatalog.cachedNormalizedQuery = query
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '');
    EmojiShortcodeCatalog.cachedExactKeyword =
      '|' + EmojiShortcodeCatalog.cachedNormalizedQuery + '|';
    EmojiShortcodeCatalog.cachedKeywordPrefix = '|' + EmojiShortcodeCatalog.cachedNormalizedQuery;
    EmojiShortcodeCatalog.cachedSegmentPrefix = '_' + EmojiShortcodeCatalog.cachedNormalizedQuery;
    return EmojiShortcodeCatalog.cachedNormalizedQuery;
  }

  private static compatibilityRankAt(index: number): number {
    if (EmojiShortcodeCatalog.cachedRawAliasQuery.length == 0) return -1;
    for (
      let aliasIndex: number = 0;
      aliasIndex < EmojiShortcodeCatalog.COMPATIBILITY_NAMES.length;
      aliasIndex++
    ) {
      if (EmojiShortcodeCatalog.COMPATIBILITY_INDICES[aliasIndex] != index) continue;
      let alias: string = EmojiShortcodeCatalog.COMPATIBILITY_NAMES[aliasIndex];
      if (alias == EmojiShortcodeCatalog.cachedRawAliasQuery) return 0;
      if (alias.indexOf(EmojiShortcodeCatalog.cachedRawAliasQuery) == 0) return 1;
      if (alias.indexOf(EmojiShortcodeCatalog.cachedRawAliasQuery) >= 0) return 5;
    }
    return -1;
  }
